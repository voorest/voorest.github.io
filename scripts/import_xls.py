"""Convert the old Mafia_stats XLS into SQL for the D1 database.

Usage:  python scripts/import_xls.py data/Mafia_stats_v2.xlsx > data/import.sql
The output contains real names, so it stays in data/ (never committed).
"""
import sys, datetime, collections
import openpyxl

ROLE_MAP = {'Citizen': 'citizen', 'Sheriff': 'sheriff', 'Doctor': 'doctor',
            'Maniac': 'maniac', 'Mafia': 'mafia', 'Don': 'don'}
TOWN = {'citizen', 'sheriff', 'doctor', 'maniac'}   # Maniac plays with the citizens


def to_date(v):
    """Dates in the sheet are dd-mm-yyyy. Some cells were auto-converted by the
    spreadsheet with day and month swapped, so we swap them back."""
    if isinstance(v, datetime.datetime):
        return datetime.date(v.year, v.day, v.month).isoformat()
    d, m, y = str(v).strip().split('-')
    return datetime.date(int(y), int(m), int(d)).isoformat()


def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    games = collections.OrderedDict()          # (date, no) -> {seats, rounds}
    players = []
    for r in wb['Games'].iter_rows(min_row=2, values_only=True):
        if not r[3]:
            continue
        key = (to_date(r[0]), int(r[1]))
        name = str(r[3]).strip()
        if name not in players:
            players.append(name)
        g = games.setdefault(key, {'seats': [], 'noms': collections.defaultdict(list), 'elim': collections.defaultdict(set)})
        g['seats'].append({'seat': int(r[2]), 'name': name, 'role': ROLE_MAP[str(r[4]).strip()],
                           'alive': int(r[5]), 'win': int(r[6])})

    for r in wb['Votes'].iter_rows(min_row=2, values_only=True):
        if r[0] is None or r[1] is None or r[4] is None:
            continue
        key = (to_date(r[0]), int(r[1]))
        g = games[key]
        rnd = int(r[2])
        g['noms'][rnd].append((int(r[3]) if r[3] is not None else None, int(r[4]), int(r[5] or 0)))
        if int(r[6] or 0) == 1:
            g['elim'][rnd].add(int(r[4]))

    problems = []
    for key, g in games.items():
        town_w = {s['win'] for s in g['seats'] if s['role'] in TOWN}
        maf_w = {s['win'] for s in g['seats'] if s['role'] not in TOWN}
        if len(town_w) != 1 or len(maf_w) != 1 or town_w == maf_w:
            problems.append(f'{key}: inconsistent team win flags')
        g['winner'] = 'town' if 1 in town_w else 'mafia'

    out = ['-- generated by scripts/import_xls.py', 'PRAGMA defer_foreign_keys = ON;']
    out.append('INSERT INTO players (id, nickname) VALUES ' +
               ', '.join(f'({i + 1}, {q(n)})' for i, n in enumerate(players)) + ';')
    pid = {n: i + 1 for i, n in enumerate(players)}
    seat_rows, nom_rows, ev_rows, game_rows = [], [], [], []
    for gi, (key, g) in enumerate(games.items(), start=1):
        game_rows.append(f"({gi}, {q(key[0])}, {key[1]}, {q(g['winner'])}, 'xls')")
        for s in g['seats']:
            seat_rows.append(f"({gi},{s['seat']},{pid[s['name']]},'{s['role']}',{s['alive']})")
        for rnd in sorted(g['noms']):
            for pos, (by, target, votes) in enumerate(g['noms'][rnd], start=1):
                nom_rows.append(f"({gi},{rnd},{pos},{'NULL' if by is None else by},{target},{votes})")
            for t in sorted(g['elim'][rnd]):
                ev_rows.append(f"({gi},{rnd},'eliminated',{t})")
    out.append('INSERT INTO games (id, date, number, winner, source) VALUES ' + ', '.join(game_rows) + ';')
    out.append('INSERT INTO game_seats (game_id, seat, player_id, role, alive) VALUES ' + ','.join(seat_rows) + ';')
    out.append('INSERT INTO nominations (game_id, round, position, by_seat, target_seat, votes) VALUES ' + ','.join(nom_rows) + ';')
    out.append('INSERT INTO round_events (game_id, round, kind, seat) VALUES ' + ','.join(ev_rows) + ';')
    print('\n'.join(out))

    # sanity report on stderr
    stats = collections.Counter(); wins = collections.Counter()
    for g in games.values():
        for s in g['seats']:
            stats[s['name']] += 1; wins[s['name']] += s['win']
    sheet = {str(r[0]).strip(): (r[1], r[2]) for r in wb['Players'].iter_rows(min_row=2, values_only=True) if r[0]}
    mism = [(n, (stats[n], wins[n]), sheet.get(n)) for n in players if sheet.get(n) != (stats[n], wins[n])]
    print(f'games={len(games)} players={len(players)} seats={len(seat_rows)} nominations={len(nom_rows)} eliminations={len(ev_rows)}', file=sys.stderr)
    print('winners:', collections.Counter(g["winner"] for g in games.values()), file=sys.stderr)
    print('dates:', sorted({k[0] for k in games}), file=sys.stderr)
    print('mismatch vs Players sheet:', mism or 'none', file=sys.stderr)
    print('problems:', problems or 'none', file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1])
